"""Single-worker analysis jobs with durable, per-user history."""
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass, field
from pathlib import Path
import shutil
from threading import Event, Lock
from typing import Dict, Optional
from uuid import uuid4

from .tracking_engine import AnalysisCancelled, TrackingEngine
from .reports import save_reports
from .history import HistoryStore, utc_now


@dataclass
class AnalysisJob:
    job_id: str
    input_path: Path
    output_dir: Path
    original_filename: str
    player_id: Optional[str]
    player_name: Optional[str]
    target_player: str
    athlete_mass_kg: Optional[float]
    input_video: Dict
    owner: str = "local-test"
    created_at: str = field(default_factory=utc_now)
    completed_at: Optional[str] = None
    status: str = "queued"
    progress: float = 0.0
    result: Optional[Dict] = None
    error: Optional[str] = None
    cancel_event: Event = field(default_factory=Event, repr=False)
    lock: Lock = field(default_factory=Lock, repr=False)

    def _data(self):
        return {
            "analysisId": self.job_id, "status": self.status,
            "progress": self.progress, "originalFilename": self.original_filename,
            "playerId": self.player_id, "playerName": self.player_name,
            "targetPlayer": self.target_player, "athleteMassKg": self.athlete_mass_kg,
            "inputVideo": dict(self.input_video), "result": self.result,
            "error": self.error, "createdAt": self.created_at,
            "completedAt": self.completed_at,
        }

    def record(self):
        with self.lock:
            return {**self._data(), "owner": self.owner}

    def snapshot(self) -> Dict:
        with self.lock:
            data = self._data()
            result = dict(self.result) if self.result is not None else None
            if result is not None and result.get("annotatedVideoFilename"):
                result["annotatedVideoUrl"] = f"/api/analyses/{self.job_id}/video"
                result.pop("annotatedVideoFilename", None)
            if result is not None and result.get("reportImages"):
                result["reportImages"] = [
                    {"title": item["title"], "url": f"/api/analyses/{self.job_id}/reports/{item['filename']}"}
                    for item in result["reportImages"]]
                result["reportArchiveUrl"] = f"/api/analyses/{self.job_id}/reports/reports.zip"
            if result is not None and result.get("coachReportFilename"):
                result["coachReportUrl"] = f"/api/analyses/{self.job_id}/reports/coach_report.pdf"
                result.pop("coachReportFilename", None)
            data["result"] = result
            return data


class AnalysisJobManager:
    """One inference worker; finished jobs are loaded from disk on demand.

    Run one API process per runtime directory. Multiple API workers would each
    have a separate inference queue and must not share this directory.
    """
    def __init__(self, runtime_dir: Path, engine: TrackingEngine):
        self.runtime_dir = runtime_dir
        self.engine = engine
        self.jobs: Dict[str, AnalysisJob] = {}
        self._jobs_lock = Lock()
        self._executor = ThreadPoolExecutor(max_workers=1, thread_name_prefix="hpt")
        self.runtime_dir.mkdir(parents=True, exist_ok=True)
        self.history = HistoryStore(self.runtime_dir)

    def create_job(self, input_path: Path, original_filename: str,
                   player_id: str, player_name: str,
                   target_player: str, athlete_mass_kg: Optional[float],
                   input_video: Dict,
                   owner: str = "local-test") -> AnalysisJob:
        job_id = uuid4().hex
        job_root = self.runtime_dir / job_id
        job_root.mkdir(parents=True, exist_ok=False)
        managed_input_path = job_root / input_path.name
        shutil.move(str(input_path), managed_input_path)
        if input_path.parent != self.runtime_dir:
            shutil.rmtree(input_path.parent, ignore_errors=True)
        job = AnalysisJob(job_id=job_id, input_path=managed_input_path,
                          output_dir=job_root / "results", original_filename=original_filename,
                           player_id=player_id, player_name=player_name,
                           target_player=target_player, athlete_mass_kg=athlete_mass_kg,
                           input_video=dict(input_video), owner=owner)
        try:
            self.history.save(job.record())
        except Exception:
            shutil.rmtree(job_root, ignore_errors=True)
            raise
        with self._jobs_lock:
            self.jobs[job_id] = job
        self._executor.submit(self._run_job, job)
        return job

    def get_job(self, job_id: str) -> Optional[AnalysisJob]:
        # IDs are generated by this service; never use an arbitrary URL path on disk.
        if len(job_id) != 32 or any(c not in "0123456789abcdef" for c in job_id):
            return None
        with self._jobs_lock:
            if job_id in self.jobs:
                return self.jobs[job_id]
        record = self.history.get(job_id)
        if record is None:
            return None
        root = self.runtime_dir / job_id
        # Loaded completed records only need output_dir; the input is not reprocessed.
        return AnalysisJob(
            job_id=job_id, input_path=root / "input.mp4", output_dir=root / "results",
            original_filename=record["originalFilename"],
            player_id=record.get("playerId"), player_name=record.get("playerName"),
            target_player=record["targetPlayer"],
            athlete_mass_kg=record.get("athleteMassKg"), input_video=record["inputVideo"],
            owner=record["owner"], created_at=record["createdAt"],
            completed_at=record.get("completedAt"), status=record["status"],
            progress=record["progress"], result=record.get("result"), error=record.get("error"))

    def delete_job(self, job_id: str) -> bool:
        job = self.get_job(job_id)
        if job is None:
            return False
        with job.lock:
            if job.status in {"queued", "processing", "cancelling"}:
                raise RuntimeError("A running analysis cannot be deleted.")
        root = self.runtime_dir / job_id
        if root.exists():
            shutil.rmtree(root)
        self.history.delete(job_id)
        with self._jobs_lock:
            self.jobs.pop(job_id, None)
        return True

    def cancel_job(self, job_id: str) -> Optional[AnalysisJob]:
        job = self.get_job(job_id)
        if job is None:
            return None
        with job.lock:
            if job.status in {"queued", "processing", "cancelling"}:
                job.status = "cancelling"
                job.cancel_event.set()
        return job

    def set_movement_moment_excluded(self, owner: str, job_id: str,
                                     event_id: str, excluded: bool) -> Optional[AnalysisJob]:
        record = self.history.set_movement_moment_excluded(
            owner, job_id, event_id, excluded
        )
        if record is None:
            return None
        job = self.get_job(job_id)
        if job is None:
            return None
        job.result = record.get("result")
        save_reports(job.result, job.output_dir)
        return job

    def shutdown(self) -> None:
        # Stop workers before another process opens this history store.
        with self._jobs_lock:
            for job in self.jobs.values():
                job.cancel_event.set()
        self._executor.shutdown(wait=True)

    def _run_job(self, job: AnalysisJob) -> None:
        try:
            with job.lock:
                if job.cancel_event.is_set():
                    raise AnalysisCancelled()
                job.status = "processing"
            self.history.save(job.record())

            def update_progress(value: float) -> None:
                with job.lock:
                    job.progress = max(job.progress, min(1.0, float(value)))

            result = self.engine.analyse(
                input_path=job.input_path, output_dir=job.output_dir,
                progress_callback=update_progress,
                cancellation_callback=job.cancel_event.is_set,
                target_player=job.target_player, athlete_mass_kg=job.athlete_mass_kg)
            result["playerId"] = job.player_id
            result["playerName"] = job.player_name
            if job.cancel_event.is_set():
                raise AnalysisCancelled()
            self.history.attach_force_velocity_baseline(
                {**job._data(), "owner": job.owner, "result": result}
            )
            save_reports(result, job.output_dir)
            if job.cancel_event.is_set():
                raise AnalysisCancelled()
            # Commit the final state before pollers can observe "completed".
            with job.lock:
                if job.cancel_event.is_set():
                    raise AnalysisCancelled()
                record = {**job._data(), "owner": job.owner, "result": result,
                          "status": "completed", "progress": 1.0, "completedAt": utc_now()}
                self.history.attach_force_velocity_baseline(record)
                self.history.save(record)
                job.result = result
                job.progress = 1.0
                job.completed_at = record["completedAt"]
                job.status = "completed"
        except AnalysisCancelled:
            shutil.rmtree(self.runtime_dir / job.job_id, ignore_errors=True)
            self._finish_error(job, "cancelled", None)
        except Exception as error:
            self._finish_error(job, "failed", str(error) or error.__class__.__name__)
        finally:
            with self._jobs_lock:
                self.jobs.pop(job.job_id, None)

    def _finish_error(self, job, status, error):
        with job.lock:
            record = {**job._data(), "owner": job.owner, "result": None,
                      "status": status, "error": error, "completedAt": utc_now()}
            self.history.save(record)
            job.status = status
            job.error = error
            job.result = None
            job.completed_at = record["completedAt"]
